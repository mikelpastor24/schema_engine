import 'dart:convert';

import 'draft.dart';
import 'json_codec.dart';
import 'json_number.dart';
import 'options.dart';
import 'schema.dart';

/// Generates Dart validators for schemas known before application compilation.
///
/// Supported boolean checks are emitted as ordinary Dart expressions and loops.
/// Schemas requiring references, decimal multiples, contains, uniqueness, or
/// unevaluated tracking use the compiled runtime engine. Diagnostics always use
/// that engine. Providing custom options to the generated class also selects
/// the runtime engine, preserving application extensions and dialect overrides.
final class SchemaCodeGenerator {
  /// Creates a generator for [schema], validating it with [options].
  SchemaCodeGenerator(this.schema, {this.options});

  /// The immutable schema document to embed in the generated source.
  final JsonSchema schema;

  /// Options used to check the input before generating source.
  ///
  /// Supply equivalent options to the generated class when they are needed for
  /// external resources or custom assertions; callbacks are never serialized.
  final SchemaOptions? options;

  final List<String> _methods = [];
  final List<String> _fields = [];

  /// Returns a standalone Dart source file containing an instance-based class.
  ///
  /// [className] must be an ASCII UpperCamelCase identifier that does not shadow
  /// a core Dart type. Throws [ArgumentError] for invalid names and forwards
  /// schema compilation errors. Repeated calls produce the same source.
  String generate({String className = 'GeneratedSchema'}) {
    if (!RegExp(r'^[A-Z][A-Za-z0-9]*$').hasMatch(className) ||
        {
          'Object',
          'String',
          'List',
          'Map',
          'Null',
          'Never',
          'Function',
          'Type',
          'Set',
          'Iterable',
          'RegExp',
          'Future',
        }.contains(className)) {
      throw ArgumentError.value(
        className,
        'className',
        'Use an UpperCamelCase class name.',
      );
    }
    schema.compile(options: options);
    _methods.clear();
    _fields.clear();
    String? root;
    try {
      root = _node(schema.value, schema.draft, root: true);
    } on _RuntimeRequired {
      _methods.clear();
      _fields.clear();
    }
    final specialized = root != null;
    return '''// Generated by schema_engine. Regenerate when the schema changes.
import 'package:schema_engine/schema_engine.dart' as engine;

/// Validates the embedded schema with generated boolean checks and diagnostics.
final class $className {
  /// Creates a reusable validator with a lazily compiled diagnostic fallback.
  $className({this.options})
      : isSpecialized = ${specialized ? 'options == null' : 'false'};

  static ${_containsExact(schema.value) ? 'final' : 'const'} _document = ${_literal(schema.value)};
  /// Options for the runtime backend, or null to use dialect defaults.
  final engine.SchemaOptions? options;
  engine.CompiledSchema? _compiled;
  engine.CompiledSchema get _runtime => _compiled ??=
      engine.JsonSchema.fromJson(_document,
        draft: engine.SchemaDraft.${schema.draft.name}).compile(options: options);

  /// Whether the generated boolean backend is active for this instance.
  final bool isSpecialized;

  /// Checks an instance, without constructing diagnostics.
  bool isValid(Object? value) => ${root == null ? '_runtime.isValid(value)' : 'isSpecialized ? $root(value) : _runtime.isValid(value)'};

  /// Returns the first assertion error, or null for a valid instance.
  engine.ValidationError? validate(Object? value,
      {engine.ValidationErrorFormatter? messageFormatter}) =>
      _runtime.validate(value, messageFormatter: messageFormatter);

  /// Returns all assertion errors for the instance.
  List<engine.ValidationError> errors(Object? value,
      {engine.ValidationErrorFormatter? messageFormatter}) =>
      _runtime.errors(value, messageFormatter: messageFormatter);

${_fields.join('\n')}
${_methods.join('\n\n')}
}
''';
  }

  String _literal(Object? value) {
    if (_containsExact(value)) {
      return 'engine.decodeJson(${_literal(encodeJson(value))})';
    }
    if (value is Map<String, Object?>) {
      return '<String, Object?>{${value.entries.map((entry) => '${_literal(entry.key)}: ${_literal(entry.value)}').join(', ')}}';
    }
    if (value is List<Object?>) {
      return '<Object?>[${value.map(_literal).join(', ')}]';
    }
    return jsonEncode(value).replaceAll(r'$', r'\$');
  }

  bool _containsExact(Object? value) =>
      value is BigInt ||
      value is JsonNumber ||
      value is Map<String, Object?> && value.values.any(_containsExact) ||
      value is List<Object?> && value.any(_containsExact);

  String _pattern(String pattern) {
    final name = '_pattern${_fields.length}';
    _fields.add('  final $name = RegExp(${_literal(pattern)}, unicode: true);');
    return name;
  }

  String _node(Object value, SchemaDraft inherited, {bool root = false}) {
    final name = '_check${_methods.length}';
    final position = _methods.length;
    _methods.add('');
    if (value is bool) {
      _methods[position] = '  bool $name(Object? value) => $value;';
      return name;
    }
    final map = value as Map<String, Object?>;
    if (_containsExact(map)) {
      throw const _RuntimeRequired();
    }
    final declared = map[r'$schema'];
    SchemaDraft draft;
    try {
      draft = !root && declared is String
          ? SchemaDraft.fromUri(declared)
          : inherited;
    } on FormatException {
      throw const _RuntimeRequired();
    }
    for (final keyword in [
      r'$ref',
      if (draft == SchemaDraft.draft202012) r'$dynamicRef',
      if (draft == SchemaDraft.draft201909) r'$recursiveRef',
      if (draft.isLegacy) ...['disallow', 'extends', 'requires'],
      if (draft.index >= SchemaDraft.draft2.index)
        draft.isLegacy ? 'divisibleBy' : 'multipleOf',
      if (draft.index >= SchemaDraft.draft6.index) 'contains',
      if (draft.supportsVocabularies) ...[
        'unevaluatedProperties',
        'unevaluatedItems',
      ],
      if (draft.supportsVocabularies) ...[
        'dependentSchemas',
        'dependentRequired',
      ] else if (draft.index >= SchemaDraft.draft3.index)
        'dependencies',
      'enum',
      'const',
    ]) {
      if (map.containsKey(keyword)) {
        throw const _RuntimeRequired();
      }
    }
    if (map['uniqueItems'] == true) {
      throw const _RuntimeRequired();
    }
    final body = <String>[];
    final typeValue = map['type'];
    if (typeValue == 'number' ||
        typeValue == 'integer' ||
        typeValue is List<Object?> &&
            (typeValue.contains('number') || typeValue.contains('integer')) ||
        [
          'minimum',
          'maximum',
          'exclusiveMinimum',
          'exclusiveMaximum',
          'maxDecimal',
        ].any(map.containsKey)) {
      final exact = '_exact$position';
      _fields.add('  engine.CompiledSchema? $exact;');
      body.add(
        '    if (value is! num && (value is BigInt || value is engine.JsonNumber)) {\n'
        '      return ($exact ??= engine.JsonSchema.fromJson(${_literal(map)},\n'
        '        draft: engine.SchemaDraft.${draft.name}).compile()).isValid(value);\n'
        '    }',
      );
    }
    void assertion(String expression) {
      final inverse =
          expression.startsWith('value is ') &&
              !expression.contains(' || ') &&
              !expression.contains(' && ')
          ? expression.replaceFirst(' is ', ' is! ')
          : '!($expression)';
      body.add('    if ($inverse) { return false; }');
    }

    final type = map['type'];
    final knownType =
        type is String && SchemaType.values.any((item) => item.jsonName == type)
        ? type
        : null;
    if (type != null) {
      final alternatives = type is List<Object?> ? type : [type];
      if (alternatives.any((item) => item is! String)) {
        throw const _RuntimeRequired();
      }
      final checks = alternatives
          .cast<String>()
          .map((item) => _type(item, draft))
          .toList();
      if (checks.isEmpty) {
        _methods[position] = '  bool $name(Object? value) => false;';
        return name;
      }
      if (!checks.contains('true')) {
        assertion(checks.join(' || '));
      }
    }
    final numbers = <String>[];
    for (final key in ['minimum', 'maximum']) {
      final bound = map[key];
      if (bound is num) {
        final lower = key == 'minimum';
        final exclusive = draft.index < SchemaDraft.draft3.index
            ? map[lower ? 'minimumCanEqual' : 'maximumCanEqual'] == false
            : !draft.supportsBooleanSchemas &&
                  map[lower ? 'exclusiveMinimum' : 'exclusiveMaximum'] == true;
        numbers.add(
          'value ${lower ? (exclusive ? '>' : '>=') : (exclusive ? '<' : '<=')} ${_literal(bound)}',
        );
      }
    }
    if (draft.supportsBooleanSchemas) {
      for (final key in ['exclusiveMinimum', 'exclusiveMaximum']) {
        if (map[key] is num) {
          numbers.add(
            'value ${key == 'exclusiveMinimum' ? '>' : '<'} ${_literal(map[key])}',
          );
        }
      }
    }
    if (map.containsKey('maxDecimal') &&
        draft.index < SchemaDraft.draft2.index) {
      throw const _RuntimeRequired();
    }
    if (numbers.isNotEmpty &&
        (knownType == null ||
            knownType == 'number' ||
            knownType == 'integer')) {
      assertion(
        knownType == null
            ? 'value is! num || (${numbers.join(' && ')})'
            : numbers.join(' && '),
      );
    }
    final strings = <String>[];
    for (final key in ['minLength', 'maxLength']) {
      if (map[key] is num) {
        final limit = map[key]! as num;
        if (key == 'minLength' && limit == 0) {
          continue;
        }
        strings.add(
          key == 'minLength' && limit == 1
              ? 'value.isNotEmpty'
              : key == 'maxLength' && limit == 0
              ? 'value.isEmpty'
              : 'value.runes.length ${key == 'minLength' ? '>=' : '<='} ${_literal(limit)}',
        );
      }
    }
    if (map['pattern'] is String &&
        (knownType == null || knownType == 'string')) {
      strings.add('${_pattern(map['pattern']! as String)}.hasMatch(value)');
    }
    if (strings.isNotEmpty && (knownType == null || knownType == 'string')) {
      assertion(
        knownType == null
            ? 'value is! String || (${strings.join(' && ')})'
            : strings.join(' && '),
      );
    }
    if (knownType == null || knownType == 'object') {
      _object(map, draft, body, assumeObject: knownType == 'object');
    }
    if (knownType == null || knownType == 'array') {
      _array(map, draft, body, assumeArray: knownType == 'array');
    }
    if (!draft.isLegacy) {
      for (final key in ['allOf', 'anyOf']) {
        if (map[key] is List<Object?>) {
          final children = (map[key]! as List<Object?>).map(
            (child) => '${_node(child!, draft)}(value)',
          );
          assertion(children.join(key == 'allOf' ? ' && ' : ' || '));
        }
      }
      if (map['oneOf'] is List<Object?>) {
        final children = (map['oneOf']! as List<Object?>).map(
          (child) => '(${_node(child!, draft)}(value) ? 1 : 0)',
        );
        assertion('(${children.join(' + ')}) == 1');
      }
      if (map.containsKey('not')) {
        assertion('!${_node(map['not']!, draft)}(value)');
      }
    }
    if (draft.index >= SchemaDraft.draft7.index && map.containsKey('if')) {
      final condition = _node(map['if']!, draft);
      final thenNode = map.containsKey('then')
          ? '${_node(map['then']!, draft)}(value)'
          : 'true';
      final elseNode = map.containsKey('else')
          ? '${_node(map['else']!, draft)}(value)'
          : 'true';
      assertion('$condition(value) ? $thenNode : $elseNode');
    }
    body.add('    return true;');
    _methods[position] =
        '  bool $name(Object? value) {\n${body.join('\n')}\n  }';
    return name;
  }

  String _type(String type, SchemaDraft draft) => switch (type) {
    'null' => 'value == null',
    'boolean' => 'value is bool',
    'string' => 'value is String',
    'array' => 'value is List<Object?>',
    'object' => '(value is Map<Object?, Object?> && (value is Map<String, Object?> || value.keys.every((key) => key is String)))',
    'number' => '(value is num && value.isFinite)',
    'integer' =>
      draft.supportsBooleanSchemas
          ? '(value is num && (value is int || value.isFinite && value == value.truncateToDouble()))'
          : 'value is int',
    _ => draft.isLegacy ? 'true' : 'false',
  };

  String _lengthFailure(num limit, {required bool minimum}) =>
      minimum && limit == 1
      ? 'value.isEmpty'
      : !minimum && limit == 0
      ? 'value.isNotEmpty'
      : 'value.length ${minimum ? '<' : '>'} ${_literal(limit)}';

  void _object(
    Map<String, Object?> map,
    SchemaDraft draft,
    List<String> body, {
    bool assumeObject = false,
  }) {
    final properties = map['properties'] as Map<String, Object?>? ?? {};
    final patterns = draft.index >= SchemaDraft.draft3.index
        ? map['patternProperties'] as Map<String, Object?>? ?? {}
        : <String, Object?>{};
    final required = !draft.isLegacy
        ? (map['required'] as List<Object?>? ?? []).cast<String>()
        : properties.entries
              .where((property) {
                final child = property.value;
                return child is Map<String, Object?> &&
                    (draft == SchemaDraft.draft3
                        ? child['required'] == true
                        : child['optional'] != true);
              })
              .map((property) => property.key)
              .toList();
    final checks = <String>[];
    for (final key in required) {
      checks.add(
        '      if (!value.containsKey(${_literal(key)})) { return false; }',
      );
    }
    if (!draft.isLegacy) {
      for (final key in ['minProperties', 'maxProperties']) {
        if (map[key] is num) {
          final limit = map[key]! as num;
          if (key == 'minProperties' && limit == 0) {
            continue;
          }
          checks.add(
            '      if (${_lengthFailure(limit, minimum: key == 'minProperties')}) { return false; }',
          );
        }
      }
    }
    for (final property in properties.entries) {
      final node = _node(property.value!, draft);
      final key = _literal(property.key);
      checks.add(
        '      if (value.containsKey($key) && !$node(value[$key])) { return false; }',
      );
    }
    final patternNodes = patterns.entries
        .map((pattern) => (_pattern(pattern.key), _node(pattern.value!, draft)))
        .toList();
    final names =
        draft.supportsBooleanSchemas && map.containsKey('propertyNames')
        ? _node(map['propertyNames']!, draft)
        : null;
    final additional = map.containsKey('additionalProperties')
        ? _node(map['additionalProperties']!, draft)
        : null;
    if (patternNodes.isNotEmpty || names != null || additional != null) {
      checks.add('      for (final key in value.keys) {');
      if (names != null) {
        checks.add('        if (!$names(key)) { return false; }');
      }
      final covered = properties.keys
          .map((key) => 'key == ${_literal(key)}')
          .join(' || ');
      if (additional != null) {
        checks.add(
          '        ${patternNodes.isEmpty ? 'final' : 'var'} covered = ${covered.isEmpty ? 'false' : covered};',
        );
      }
      for (final pattern in patternNodes) {
        checks.add(
          '        if (${pattern.$1}.hasMatch(key as String)) { ${additional == null ? '' : 'covered = true;'} if (!${pattern.$2}(value[key])) { return false; } }',
        );
      }
      if (additional != null) {
        checks.add(
          '        if (!covered && !$additional(value[key])) { return false; }',
        );
      }
      checks.add('      }');
    }
    if (checks.isNotEmpty) {
      body.add(
        assumeObject
            ? checks.join('\n')
            : '    if (value is Map<Object?, Object?>) {\n${checks.join('\n')}\n    }',
      );
    }
  }

  void _array(
    Map<String, Object?> map,
    SchemaDraft draft,
    List<String> body, {
    bool assumeArray = false,
  }) {
    final checks = <String>[];
    for (final key in ['minItems', 'maxItems']) {
      if (map[key] is num) {
        final limit = map[key]! as num;
        if (key == 'minItems' && limit == 0) {
          continue;
        }
        checks.add(
          '      if (${_lengthFailure(limit, minimum: key == 'minItems')}) { return false; }',
        );
      }
    }
    final tupleKey = draft == SchemaDraft.draft202012 ? 'prefixItems' : 'items';
    final tuple = map[tupleKey];
    var prefix = 0;
    if (tuple is List<Object?>) {
      prefix = tuple.length;
      for (var i = 0; i < tuple.length; i++) {
        checks.add(
          '      if (value.length > $i && !${_node(tuple[i]!, draft)}(value[$i])) { return false; }',
        );
      }
    }
    final restKey = draft == SchemaDraft.draft202012 || tuple is! List<Object?>
        ? 'items'
        : draft.index < SchemaDraft.draft3.index
        ? 'additionalProperties'
        : 'additionalItems';
    final rest = map[restKey];
    if (rest is Map<String, Object?> || rest is bool) {
      final node = _node(rest!, draft);
      checks.add(
        '      for (var i = $prefix; i < value.length; i++) { if (!$node(value[i])) { return false; } }',
      );
    }
    if (checks.isNotEmpty) {
      body.add(
        assumeArray
            ? checks.join('\n')
            : '    if (value is List<Object?>) {\n${checks.join('\n')}\n    }',
      );
    }
  }
}

final class _RuntimeRequired implements Exception {
  const _RuntimeRequired();
}
